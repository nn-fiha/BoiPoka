// Finds covers on Open Library (searched by the original title, so Bangla books match too)
// and then Google Books for catalog books that don't have one yet,
// and writes supabase/migrations/009_google_covers.sql to run in the Supabase SQL editor.
// Usage: node --env-file=.env scripts/fill-covers.mjs
// Google Books is only searched when GOOGLE_BOOKS_API_KEY is in .env (free, from Google Cloud).
import { writeFileSync } from "node:fs";

const { VITE_SUPABASE_URL: base, VITE_SUPABASE_ANON_KEY: anonKey, GOOGLE_BOOKS_API_KEY: googleKey } = process.env;
if (!base || !anonKey) throw new Error("Run with --env-file=.env so the Supabase URL and key are set");

const sql = (value) => `'${String(value).replace(/'/g, "''")}'`;
// Letters only (Latin or Bangla), lower case, so "Pather Panchali" matches "Pather panchali:"
const simplify = (text = "") =>
  text
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9ঀ-৿]/g, "");
const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

const response = await fetch(`${base}/rest/v1/books?select=id,title,author&cover_url=is.null`, { headers: { apikey: anonKey } });
const books = await response.json();
console.log(`${books.length} books without a cover\n`);

// Title must match from the start and the author must share the surname, so a wrong cover never slips in
const matches = (book, title, authors = []) => {
  const want = simplify(book.title);
  const found = simplify(title);
  const surname = simplify(book.author.trim().split(/\s+/).at(-1));
  const titleOk = found === want || (found.startsWith(want) && want.length >= 4);
  // Bangla books are often listed with the author in English letters, so an exact Bangla title is enough on its own
  const bangla = /[\u0980-\u09ff]/.test(book.title);
  return titleOk && (bangla || authors.some((name) => simplify(name).includes(surname)));
};

// Covers checked by eye and found to be blank pages
const BLANK_COVERS = new Set([13202688]);

const openLibrary = async (book) => {
  const params = new URLSearchParams({ q: book.title, limit: "10", fields: "title,author_name,cover_i" });
  const res = await fetch(`https://openlibrary.org/search.json?${params}`, { headers: { "User-Agent": "BoiPoka cover finder" } });
  if (!res.ok) return null;
  const { docs = [] } = await res.json();
  const match = docs.find((doc) => doc.cover_i && !BLANK_COVERS.has(doc.cover_i) && matches(book, doc.title, doc.author_name));
  return match ? `https://covers.openlibrary.org/b/id/${match.cover_i}-M.jpg` : null;
};

const googleBooks = async (book) => {
  const params = new URLSearchParams({ q: `intitle:${book.title} inauthor:${book.author}`, maxResults: "10", printType: "books" });
  params.set("key", googleKey);
  for (let attempt = 0; attempt < 4; attempt++) {
    const res = await fetch(`https://www.googleapis.com/books/v1/volumes?${params}`);
    if (res.status === 429) {
      await sleep(5000 * (attempt + 1));
      continue;
    }
    if (!res.ok) return null;
    const { items = [] } = await res.json();
    const match = items.find(({ volumeInfo: v }) => v.imageLinks?.thumbnail && matches(book, v.title, v.authors));
    return match?.volumeInfo.imageLinks.thumbnail.replace("http://", "https://").replace("&edge=curl", "") || null;
  }
  return null;
};

const updates = [];
for (const book of books) {
  const fromOpenLibrary = await openLibrary(book);
  const cover = fromOpenLibrary || (googleKey ? await googleBooks(book) : null);
  console.log(`${cover ? (fromOpenLibrary ? "OL   " : "GB   ") : "  -  "}  ${book.title}`);
  if (cover) updates.push(`update public.books set cover_url = ${sql(cover)} where id = ${sql(book.id)} and cover_url is null;`);
  await sleep(400);
}

writeFileSync(
  new URL("../supabase/migrations/009_google_covers.sql", import.meta.url),
  `-- Covers found on Open Library and Google Books (generated by scripts/fill-covers.mjs)
-- Only fills books that still have no cover, so uploaded photos are never replaced.
${updates.join("\n")}
`
);
console.log(`\nFound ${updates.length} of ${books.length} covers. Wrote supabase/migrations/009_google_covers.sql`);
