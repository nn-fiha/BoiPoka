// Turns the original BoiPoka mock catalog into supabase/seed.sql
// Usage: node scripts/generate-seed.mjs
import { writeFileSync } from "node:fs";
import MockData from "./MockData.js";

const GENRE_ALIASES = { "Sci-Fiction": "Science Fiction" };
const sql = (value) => (value == null ? "null" : `'${String(value).replace(/'/g, "''")}'`);
// The mock data used placeholder English publishers; keep only real (Bangla) ones
const realPublisher = (publisher) => (/[ঀ-৿]/.test(publisher) ? publisher : null);

const rows = MockData.map((book) =>
  [
    sql(book.book_title),
    sql(book.author),
    sql(GENRE_ALIASES[book.genre] || book.genre),
    sql(book.language),
    book.pages,
    sql(realPublisher(book.publisher)),
    sql(book.images),
  ].join(", ")
);

const output = `-- Starter catalog from the original BoiPoka mock data (generated by scripts/generate-seed.mjs)
insert into public.books (title, author, genre, language, pages, publisher, cover_url) values
${rows.map((row) => `  (${row})`).join(",\n")};
`;

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), output);
console.log(`Wrote ${rows.length} books to supabase/seed.sql`);
