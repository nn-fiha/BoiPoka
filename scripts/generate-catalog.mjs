// Looks up the books in scripts/catalog-list.mjs on Open Library (cover, pages, ISBN)
// and writes supabase/migrations/007_more_books.sql. Books already in the catalog are skipped.
// Usage: node scripts/generate-catalog.mjs
import { writeFileSync } from "node:fs";
import { BANGLA, ENGLISH } from "./catalog-list.mjs";

const sql = (value) => (value == null ? "null" : `'${String(value).replace(/'/g, "''")}'`);
const simplify = (text) =>
  text
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]/g, "");

// Finds a work whose title and author both match, so a wrong book never gets attached
const lookup = async (title, author) => {
  const params = new URLSearchParams({
    title,
    author,
    limit: "5",
    fields: "key,title,author_name,cover_i,number_of_pages_median,isbn,first_publish_year",
  });
  for (let attempt = 0; attempt < 3; attempt++) {
    const response = await fetch(`https://openlibrary.org/search.json?${params}`, {
      headers: {
        "User-Agent": "BoiPoka catalog builder (boi-poka.vercel.app)",
      },
    });
    if (!response.ok) {
      await new Promise((resolve) => setTimeout(resolve, 2000));
      continue;
    }
    const { docs } = await response.json();
    const wantTitle = simplify(title);
    const surname = simplify(author.split(" ").at(-1));
    return docs.find(
      (doc) =>
        simplify(doc.title).startsWith(wantTitle.slice(0, 8)) &&
        // Open Library already filtered by author; names in other scripts (村上春樹) can't be compared
        (doc.author_name || []).some((name) => simplify(name).includes(surname) || !/[a-z]/i.test(name))
    );
  }
  return undefined;
};

const rows = [];
const books = [
  ...BANGLA.map(([title, author, genre, search]) => ({
    title,
    author,
    genre,
    language: "Bangla",
    search,
  })),
  ...ENGLISH.map(([title, author, genre]) => ({
    title,
    author,
    genre,
    language: "English",
    search: `${title}|${author}`,
  })),
];

for (const book of books) {
  const [searchTitle, searchAuthor] = book.search?.split("|") || [];
  const doc = book.search ? await lookup(searchTitle, searchAuthor) : undefined;
  rows.push({
    ...book,
    pages: doc?.number_of_pages_median || null,
    isbn: doc?.isbn?.[0] || null,
    openlibrary_key: doc?.key || null,
    cover_url: doc?.cover_i ? `https://covers.openlibrary.org/b/id/${doc.cover_i}-M.jpg` : null,
  });
  console.log(`${doc?.cover_i ? "cover" : doc ? "found" : "  -  "}  ${book.title}`);
  await new Promise((resolve) => setTimeout(resolve, 350));
}

const values = rows
  .map((b) =>
    [b.title, b.author, b.genre, b.language]
      .map(sql)
      .concat(b.pages ?? "null", sql(b.isbn), sql(b.openlibrary_key), sql(b.cover_url))
      .join(", ")
  )
  .map((row) => `  (${row})`)
  .join(",\n");

const output = `-- More books for the shared catalog (generated by scripts/generate-catalog.mjs)
-- Safe to run more than once: books already in the catalog are skipped.

-- Tidy the starter catalog: stray spaces, and genres that didn't fit the book
update public.books set title = btrim(title, E' \\t'), author = btrim(author, E' \\t')
  where title <> btrim(title, E' \\t') or author <> btrim(author, E' \\t');
update public.books set genre = 'Poetry' where created_by is null and title in ('গীতাঞ্জলী', 'বলাকা');
update public.books set genre = 'Fiction' where created_by is null and title in ('প্রথম আলো (১)', 'সেই সময় (অখণ্ড)', 'রবীন্দ্রনাথের ছোটগল্প', 'গল্পগুচ্ছ', 'ডাকঘর', 'যোগাযোগ', 'গাভী বিত্তান্ত');
update public.books set genre = 'Children' where created_by is null and title = 'কাকাবাবু ও আশ্চর্য দ্বীপ';
update public.books set author = 'রবীন্দ্রনাথ ঠাকুর' where created_by is null and title = 'যোগাযোগ' and author = 'Jodi Mateu';

insert into public.books (title, author, genre, language, pages, isbn, openlibrary_key, cover_url)
select v.title, v.author, v.genre, v.language, v.pages, v.isbn, v.openlibrary_key, v.cover_url
from (values
${values}
) as v (title, author, genre, language, pages, isbn, openlibrary_key, cover_url)
where not exists (
  select 1 from public.books b
  where lower(b.title) = lower(v.title) and lower(b.author) = lower(v.author)
     or (v.openlibrary_key is not null and b.openlibrary_key = v.openlibrary_key)
);
`;

writeFileSync(new URL("../supabase/migrations/007_more_books.sql", import.meta.url), output);
const covers = rows.filter((b) => b.cover_url).length;
console.log(`\nWrote ${rows.length} books (${covers} with covers) to supabase/migrations/007_more_books.sql`);
